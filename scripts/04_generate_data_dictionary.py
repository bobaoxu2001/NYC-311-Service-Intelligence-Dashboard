"""
04_generate_data_dictionary.py
------------------------------
Generate docs/data_dictionary.md by introspecting the clean dataset:
column name, type, null rate, an example value, and a curated description.
Also lists every Tableau extract file and its columns.
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CLEAN_PATH = ROOT / "data" / "processed" / "311_clean.parquet"
TABLEAU_DIR = ROOT / "data" / "tableau"
OUT_PATH = ROOT / "docs" / "data_dictionary.md"

DESCRIPTIONS = {
    "unique_key": "Unique identifier of the 311 service request (source system).",
    "created_date": "Timestamp the request was created.",
    "closed_date": "Timestamp the request was closed (null if still open).",
    "agency": "Responding agency acronym (e.g. NYPD, HPD, DSNY).",
    "agency_name": "Full name of the responding agency.",
    "complaint_type": "Standardized complaint category (title-cased in cleaning).",
    "descriptor": "More specific sub-category of the complaint.",
    "incident_zip": "Incident ZIP code; only valid 5-digit NYC ZIPs (100xx-119xx) kept.",
    "city": "City field as reported (often the borough name).",
    "borough": "Normalized borough; 'Unspecified' when the source had no borough.",
    "latitude": "Incident latitude; nulled if outside the NYC bounding box.",
    "longitude": "Incident longitude; nulled if outside the NYC bounding box.",
    "status": "Request status from the source system (Open, Closed, In Progress...).",
    "location_type": "Type of location (Street/Sidewalk, Residential Building...).",
    "community_board": "NYC community board of the incident.",
    "council_district": "NYC council district number.",
    "police_precinct": "NYPD precinct of the incident.",
    "open_data_channel_type": "How the request was submitted (Phone, Online, Mobile...).",
    "created_year": "Calendar year of created_date.",
    "created_month": "Year-month of created_date (YYYY-MM), for trend charts.",
    "created_month_name": "Month name of created_date.",
    "created_week": "ISO week number of created_date.",
    "created_day_of_week": "Day name of created_date.",
    "created_hour": "Hour of day (0-23) of created_date.",
    "is_weekend": "True if created on Saturday or Sunday.",
    "resolution_hours": "closed_date - created_date, in hours (null if open).",
    "resolution_days": "closed_date - created_date, in days (null if open).",
    "resolution_days_capped": "resolution_days capped at the 99th percentile; use for averages.",
    "is_resolution_outlier": "True if resolution_days exceeds the 99th percentile.",
    "is_closed": "True if status is Closed.",
    "closed_within_1_day": "True if closed within 1 day of creation.",
    "closed_within_3_days": "True if closed within 3 days of creation.",
    "closed_within_7_days": "True if closed within 7 days of creation.",
    "has_valid_location": "True if coordinates fall inside the NYC bounding box.",
}


def example_value(s: pd.Series) -> str:
    nonnull = s.dropna()
    if nonnull.empty:
        return ""
    v = nonnull.iloc[0]
    return str(v)[:40]


def main():
    df = pd.read_parquet(CLEAN_PATH)
    n = len(df)

    lines = [
        "# Data Dictionary",
        "",
        "Generated by `scripts/04_generate_data_dictionary.py`.",
        "",
        "## Clean analytical dataset (`data/processed/311_clean.parquet`)",
        "",
        f"Rows: **{n:,}** | Columns: **{len(df.columns)}**",
        "",
        "| Column | Type | Null % | Example | Description |",
        "|---|---|---:|---|---|",
    ]
    for col in df.columns:
        null_pct = 100 * df[col].isna().mean()
        desc = DESCRIPTIONS.get(col, "")
        lines.append(
            f"| `{col}` | {df[col].dtype} | {null_pct:.1f}% "
            f"| {example_value(df[col])} | {desc} |"
        )

    lines += ["", "## Tableau extract files (`data/tableau/`)", ""]
    for path in sorted(TABLEAU_DIR.glob("*.csv")):
        head = pd.read_csv(path, nrows=5)
        rows = sum(1 for _ in open(path)) - 1
        lines += [
            f"### `{path.name}`",
            "",
            f"Rows: {rows:,} | Columns: {', '.join(f'`{c}`' for c in head.columns)}",
            "",
        ]

    lines += [
        "## Metric definitions",
        "",
        "- **Median resolution days** — median of `resolution_days` over *closed* requests.",
        "  Preferred over the mean because resolution time is heavily right-skewed.",
        "- **Average resolution days** — mean of `resolution_days_capped` (outliers capped",
        "  at the 99th percentile) over closed requests; provided for reference only.",
        "- **Open rate** — open requests / total requests in the group.",
        "- **% closed within N days** — requests closed within N days / total requests.",
        "- **Service Pressure Score (0-100)** — composite of volume, speed, and backlog:",
        "  `0.4 * norm(request_count) + 0.4 * norm(median_resolution_days) + 0.2 * norm(open_rate)`,",
        "  where `norm` is min-max normalization to 0-100 within the geographic/categorical level.",
        "",
        "## Fields intentionally excluded",
        "",
        "- `incident_address`, `intersection_street_1/2` — street-level detail is not needed",
        "  for the dashboard and avoids exposing precise addresses.",
        "- State-plane coordinates, park fields — redundant with latitude/longitude.",
    ]

    OUT_PATH.write_text("\n".join(lines))
    print(f"Data dictionary -> {OUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
